  if(pause>0){ pause-=dt; if(pause<=0) resetCar(); return; }
  const k=turn(s), target=clamp(k*20,-1,1), tight=smooth(.02,.027,Math.abs(k));
  drift+=(target-drift)*Math.min(1,dt*3.5);
  const [tx,ty]=tan(s), climb=Math.abs(ty);
  const v=96*(1-.38*Math.min(1,Math.abs(target)))*(1-.25*climb);
  s+=v*dt; dist+=v*dt*(1+.4*Math.abs(drift));
  if(s>=PL){ pause=1.2; car.a=0; return; }
  [car.x,car.y]=at(s); car.k=depth(car.y);
